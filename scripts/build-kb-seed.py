#!/usr/bin/env python3
"""Generates init-scripts/vectordb/02-seed-manuals.sql from the raw-layer originals.

Single source of truth: knowledge/raw-manuals/<source>/<doc_id>.md (front matter + one `## section`
per chunk) and knowledge/kb-curation.json (SAP references, OEM ↔ SAP part mapping). Chunk text is
copied verbatim, so `make smoke` can prove that the index is contained in the raw layer.
Run `make kb-seed` after editing either input; never edit the generated SQL by hand.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "knowledge" / "raw-manuals"
CURATION = ROOT / "knowledge" / "kb-curation.json"
OUTPUT = ROOT / "init-scripts" / "vectordb" / "02-seed-manuals.sql"
DOC_FIELDS = ("doc_id", "title", "applies_to", "doc_type", "issuing_site", "revision", "language", "classification")
XREF_FIELDS = ("oem_part_no", "matnr", "description_en", "description_es", "description_pt", "base_uom")
QUOTE_TAG = "$md$"


def literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def parse_manual(path: Path) -> tuple[dict[str, str], list[tuple[str, str]]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---":
        raise SystemExit(f"{path}: missing front matter")
    end = lines.index("---", 1)
    meta = dict(line.split(": ", 1) for line in lines[1:end])
    if meta.get("doc_id") != path.stem:
        raise SystemExit(f"{path}: doc_id '{meta.get('doc_id')}' must match the file name")

    sections: list[tuple[str, str]] = []
    heading, body = None, []
    for line in lines[end + 1:] + ["## "]:  # sentinel flushes the last section
        if line.startswith("## "):
            if heading:
                sections.append((heading, "\n".join(body).strip("\n")))
            heading, body = line[3:].strip(), []
        elif heading:
            body.append(line)
    return meta, sections


def main() -> None:
    curation = json.loads(CURATION.read_text(encoding="utf-8"))
    manuals = sorted(RAW.glob("*/*.md"))
    curated = curation["documents"]
    missing = {p.stem for p in manuals} ^ set(curated)
    if missing:
        raise SystemExit(f"raw manuals and kb-curation.json disagree on: {sorted(missing)}")

    documents, chunks = [], []
    for path in manuals:
        meta, sections = parse_manual(path)
        uri = f"s3://raw-manuals/{path.relative_to(RAW).as_posix()}"
        documents.append("(" + ", ".join([*(literal(meta[f]) for f in DOC_FIELDS), literal(uri)]) + ")")
        refs = literal(json.dumps(curated[path.stem]["sap_refs"], ensure_ascii=False))
        for number, (section, content) in enumerate(sections, start=1):
            if QUOTE_TAG in content:
                raise SystemExit(f"{path}: content contains the reserved quote tag {QUOTE_TAG}")
            chunks.append(f"({literal(meta['doc_id'])}, {number}, {literal(section)}, {refs}::jsonb,\n"
                          f"{QUOTE_TAG}{content}{QUOTE_TAG})")
    xrefs = ["(" + ", ".join(literal(x[f]) for f in XREF_FIELDS) + ")" for x in curation["part_xref"]]

    OUTPUT.write_text(
        "-- GENERATED by scripts/build-kb-seed.py from knowledge/raw-manuals + knowledge/kb-curation.json.\n"
        "-- Do not edit by hand: run `make kb-seed`. SYNTHETIC corpus, simulation only.\n"
        "-- Embeddings stay NULL until the backend runs POST /api/v1/kb/embed (make embed).\n\n"
        f"INSERT INTO kb.documents ({', '.join(DOC_FIELDS)}, source_uri) VALUES\n    "
        + ",\n    ".join(documents) + ";\n\n"
        f"INSERT INTO kb.part_xref ({', '.join(XREF_FIELDS)}) VALUES\n    "
        + ",\n    ".join(xrefs) + ";\n\n"
        "INSERT INTO kb.chunks (doc_id, chunk_no, section, sap_refs, content) VALUES\n"
        + ",\n\n".join(chunks) + ";\n",
        encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(documents)} documents, {len(chunks)} chunks, {len(xrefs)} part xrefs")


if __name__ == "__main__":
    main()
